import { readFile, writeFile } from "node:fs/promises";
import { runInNewContext } from "node:vm";

const root = new URL("../public/web-development-pl-lab/", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");

async function replaceAssets(html, pattern, inline) {
  const matches = [...html.matchAll(pattern)];
  const sources = await Promise.all(matches.map(match => read(match[1])));
  let offset = 0;
  return html.replace(pattern, () => {
    const index = offset++;
    return inline(matches[index], sources[index]);
  });
}

const curriculum = {};
runInNewContext(await read("assets/js/curriculum.js"), curriculum);
await writeFile(new URL("data/learning-content.json", root), JSON.stringify(curriculum.PLLab.curriculum, null, 2) + "\n");

let page = await read("index.html");
page = page.replace(/^\s*<a[^\n]+ data-offline-download>[^\n]+<\/a>\n/mu, "\n");
page = await replaceAssets(page, /<link rel="icon" href="(\.\/assets\/images\/[\w.-]+\.svg)" type="image\/svg\+xml">/gu,
  (_, source) => `<link rel="icon" type="image/svg+xml" href="data:image/svg+xml;base64,${Buffer.from(source).toString("base64")}">`);
page = await replaceAssets(page, /<link rel="stylesheet" href="(\.\/assets\/css\/[\w.-]+\.css)">/gu,
  (_, source) => `<style>\n${source.replace(/<\/style/giu, "<\\/style")}\n</style>`);
page = await replaceAssets(page, /<a href="(\.\/docs\/[\w.-]+\.md)" data-offline-resource>/gu,
  (match, source) => `<a href="data:text/markdown;charset=utf-8;base64,${Buffer.from(source).toString("base64")}" download="${match[1].split("/").at(-1)}">`);

const scripts = [];
page = await replaceAssets(page, /<script defer src="(\.\/assets\/js\/[\w.-]+\.js)"><\/script>/gu,
  (_, source) => { scripts.push(source.trim().replace(/<\/script/giu, "<\\/script")); return ""; });
page = page.replace(/\n[ \t]*\n(?:[ \t]*\n)+(?=<\/head>)/u, "\n");
page = page.replace("</body>", `<script>\n${scripts.join("\n\n")}\n</script>\n</body>`);
page = page.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by npm run build:pl-lab. Edit index.html and assets instead. -->");
await writeFile(new URL("standalone.html", root), page);
