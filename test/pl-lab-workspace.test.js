import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createContext, runInContext } from "node:vm";
import { test } from "node:test";

const root = new URL("../public/web-development-pl-lab/", import.meta.url);
const context = createContext({ TextEncoder });
for (const name of ["curriculum", "plan-model", "workspace", "requirements", "design", "azure", "planning", "practice"]) {
  const filename = new URL(`assets/js/${name}.js`, root);
  runInContext(await readFile(filename, "utf8"), context, { filename: filename.pathname });
}
const { workspace, plan, curriculum, chapters, validators } = context.PLLab;
const clone = data => JSON.parse(JSON.stringify(data));

test("all 13 chapter anchors work as a static table of contents and every exercise registers", async () => {
  const html = await readFile(new URL("index.html", root), "utf8");
  assert.equal(curriculum.chapters.length, 13);
  for (const { id, requires } of curriculum.chapters) {
    assert.ok(html.includes(`href="#chapter-${id}"`));
    assert.ok(html.includes(`id="chapter-${id}"`));
    assert.ok(requires.every(dependency => dependency < id));
    if (id === "00") continue;
    assert.equal(typeof chapters[id], "function");
    assert.equal(typeof validators[id], "function");
  }
});

test("versioned backups round-trip both separate projects, progress and updated artifacts", () => {
  const state = workspace.fresh();
  state.plans.sample = plan.samplePlan("sample");
  state.progress["06"] = true;
  state.planMode = "final";
  workspace.recordArtifact(state, "06", "自分の WBS", "初稿");
  workspace.recordArtifact(state, "06", "自分の WBS", "改訂\n<script>literal text</script>");
  const restored = workspace.parse("\uFEFF" + JSON.stringify(state));
  assert.deepEqual(clone(restored), clone(state));
  assert.equal(restored.plans.final.tasks.length, 1);
  assert.ok(restored.plans.sample.tasks.length > 25);
  assert.equal(workspace.artifacts(restored).length, 1);
});

test("restoration rejects malformed chapter data, formats, versions and swapped plans", () => {
  const state = clone(workspace.fresh());
  for (const invalid of [
    { ...state, version: 9 },
    { ...state, planMode: "unknown" },
    { ...state, progress: { "02": "true" } },
    { ...state, answers: { "99": {} } },
    { ...state, answers: { "02": null } },
    { ...state, plans: { sample: state.plans.final, final: state.plans.sample } },
    { ...state, artifacts: { "02": [{ title: "", markdown: "body" }] } },
  ]) assert.throws(() => workspace.parse(JSON.stringify(invalid)));
  assert.throws(() => workspace.parse("{"));
  assert.throws(() => workspace.parse(" ".repeat(workspace.maxBackupBytes + 1)));
});

test("single-file distribution has inline assets and no runtime network loader", async () => {
  const html = await readFile(new URL("standalone.html", root), "utf8");
  assert.match(html, /Generated by npm run build:pl-lab/);
  assert.match(html, /data:image\/svg\+xml;base64,/);
  assert.doesNotMatch(html, /<(?:link|script)[^>]*(?:href|src)="\.\/assets\//);
  assert.doesNotMatch(html, /<script[^>]+\bsrc=/);
  assert.doesNotMatch(html, /\bfetch\s*\(/);
  const inline = html.match(/<script>\n([\s\S]*?)\n<\/script>/);
  assert.ok(inline);
  // Compile the exact text that will run in an offline document.
  assert.doesNotThrow(() => new Function(inline[1]));
});
